-- Solo datos sintéticos. Ejecutar tras 0006; al terminar se deshace todo.
begin;
do $$
declare
  a uuid := gen_random_uuid(); b uuid := gen_random_uuid(); c uuid := gen_random_uuid(); d uuid := gen_random_uuid();
  aa text := 'a_' || left(replace(a::text, '-', ''), 8);
  ab text := 'b_' || left(replace(b::text, '-', ''), 8);
  ac text := 'c_' || left(replace(c::text, '-', ''), 8);
  grupo uuid := gen_random_uuid(); otro uuid := gen_random_uuid();
  privada uuid := gen_random_uuid(); compartida uuid := gen_random_uuid(); ajena uuid := gen_random_uuid(); logro uuid := gen_random_uuid();
  comentario uuid; e text; n integer; i integer; r record;
  texto jsonb := '{"v":1,"tipo":"texto","titulo":"Publicación","texto":"Una publicación de prueba"}';
begin
  insert into auth.users(id, email, aud, role, created_at, updated_at)
    select x, x::text || '@appfit-pruebas.invalid', 'authenticated', 'authenticated', now(), now() from unnest(array[a,b,c,d]) x;
  perform set_config('request.jwt.claims', '{}', true);
  begin perform public.comunidades('', false); e := null; exception when others then e := sqlerrm; end;
  assert e = 'sin_sesion', 'No hay comunidades sin sesión';
  perform set_config('request.jwt.claims', json_build_object('sub', d)::text, true);
  begin perform public.crear_comunidad(grupo, 'Pruebas', ''); e := null; exception when others then e := sqlerrm; end;
  assert e = 'sin_perfil', 'No hay creación sin perfil';
  perform set_config('request.jwt.claims', json_build_object('sub', a)::text, true); perform public.crear_perfil(aa, 'Ana', true);
  update public.perfiles set avisos_vistos = now() - interval '1 day' where user_id = a;
  perform set_config('request.jwt.claims', json_build_object('sub', b)::text, true); perform public.crear_perfil(ab, 'Beto', true);
  perform set_config('request.jwt.claims', json_build_object('sub', c)::text, true); perform public.crear_perfil(ac, 'Carla', true);
  perform set_config('request.jwt.claims', json_build_object('sub', a)::text, true);
  perform public.crear_comunidad(grupo, 'Pruebas ' || grupo, 'Entreno y caminatas');
  perform public.crear_comunidad(grupo, 'Pruebas ' || grupo, 'Reintento');
  select * into r from public.comunidades(grupo::text, true);
  assert r.id = grupo and r.miembros = 1 and r.mia and r.unida, 'La creadora es miembro y el reintento no duplica';
  begin perform public.salir_comunidad(grupo); e := null; exception when others then e := sqlerrm; end;
  assert e = 'creador_no_puede_salir', 'La comunidad no queda sin su creadora';
  perform public.publicar(privada, 'texto', now(), texto);
  perform public.publicar_comunidad(compartida, 'texto', now(), texto, grupo);
  perform public.publicar_comunidad(compartida, 'texto', now(), texto, grupo);
  select count(*) into n from public.publicaciones where id = compartida;
  assert n = 1, 'Publicar en comunidad es idempotente';
  begin perform public.publicar(compartida, 'texto', now(), texto); e := null; exception when others then e := sqlerrm; end;
  assert e = 'publicacion_no_valida', 'Un reintento no cambia la audiencia';
  begin perform public.publicar_comunidad(privada, 'texto', now(), texto, grupo); e := null; exception when others then e := sqlerrm; end;
  assert e = 'publicacion_no_valida', 'Tampoco de seguidores a comunidad';
  begin perform public.publicar(gen_random_uuid(), 'texto', now(), '{"v":1,"tipo":"texto","titulo":"x","texto":" "}'); e := null; exception when others then e := sqlerrm; end;
  assert e = 'publicacion_no_valida', 'No se publica texto vacío';
  begin perform public.publicar(gen_random_uuid(), 'texto', now(), jsonb_build_object('v',1,'tipo','texto','titulo','x','texto',repeat('x',2001))); e := null; exception when others then e := sqlerrm; end;
  assert e = 'publicacion_no_valida', 'No se publica texto largo';
  begin perform public.publicar(gen_random_uuid(), 'logro', now(), '{"v":1,"tipo":"logro","titulo":"Entrenos","logroId":"entrenos","grupo":"entreno","nivel":6,"descripcion":"Prueba"}'); e := null; exception when others then e := sqlerrm; end;
  assert e = 'publicacion_no_valida', 'Nivel de logro acotado';
  perform public.publicar(logro, 'logro', now(), '{"v":1,"tipo":"logro","titulo":"Entrenos","logroId":"entrenos","grupo":"entreno","nivel":1,"descripcion":"10 entrenos"}');

  -- Seguir a la autora no da acceso a sus publicaciones de comunidad.
  perform set_config('request.jwt.claims', json_build_object('sub', b)::text, true);
  select * into r from public.comunidades(grupo::text, false);
  assert r.id = grupo and not r.unida, 'Se descubre sin seguir ni unirse';
  begin perform public.crear_comunidad(gen_random_uuid(), 'PRUEBAS ' || grupo, ''); e := null; exception when others then e := sqlerrm; end;
  assert e = 'comunidad_ocupada', 'Nombre único sin distinguir mayúsculas';
  perform public.pedir_seguir(aa);
  perform set_config('request.jwt.claims', json_build_object('sub', a)::text, true); perform public.responder_solicitud(ab, true);
  perform set_config('request.jwt.claims', json_build_object('sub', b)::text, true);
  select count(*) into n from public.feed(null, 30); assert n = 2, 'Feed solo de seguidores, sin comunidad';
  select count(*) into n from public.publicaciones_de(aa, null, 30); assert n = 2, 'El perfil tampoco filtra comunidades';
  begin perform public.publicaciones_comunidad(grupo, null, 20); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_miembro', 'Un seguidor no miembro no ve el feed de comunidad';
  begin perform public.publicar_comunidad(ajena, 'texto', now(), texto, grupo); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_miembro', 'Un no miembro no publica';
  begin perform public.comentar(compartida, 'No debería poder'); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'No adivina un UUID para comentar';
  begin perform public.reaccionar(compartida); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'Ni para reaccionar';

  -- Una persona que NO sigue a la autora puede interactuar tras unirse.
  perform set_config('request.jwt.claims', json_build_object('sub', c)::text, true);
  perform public.unirse_comunidad(grupo); perform public.unirse_comunidad(grupo);
  select * into r from public.comunidades(grupo::text, true); assert r.miembros = 2 and r.unida, 'Unirse dos veces no duplica';
  select * into r from public.publicaciones_comunidad(grupo, null, 20); assert r.id = compartida and r.alias = aa, 'Miembro sin seguimiento ve lo compartido';
  select count(*) into n from public.feed(null, 20); assert n = 0, 'No se abre el resto del perfil privado';
  begin perform public.comentarios_de(privada); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'La comunidad no da acceso a publicaciones de seguidores';
  perform public.reaccionar(compartida); comentario := public.comentar(compartida, '¡Buen trabajo!');
  perform public.publicar_comunidad(ajena, 'texto', now(), texto, grupo);
  perform public.crear_comunidad(otro, 'Otra ' || otro, '');
  select count(*) into n from public.publicaciones_comunidad(otro, null, 20); assert n = 0, 'Cada feed queda en su comunidad';
  perform set_config('request.jwt.claims', json_build_object('sub', a)::text, true);
  select * into r from public.social_fila(a, compartida); assert r.reacciones = 1 and r.comentarios = 1, 'Recuentos de miembros';
  assert public.avisos() ->> 'nuevos' = '2', 'Avisos de miembros sin seguimiento';
  perform public.bloquear(ac);
  select count(*) into n from public.publicaciones_comunidad(grupo, null, 20); assert n = 1, 'Las publicaciones bloqueadas desaparecen';
  select * into r from public.social_fila(a, compartida); assert r.reacciones = 0 and r.comentarios = 0, 'Tampoco se cuentan sus interacciones';
  perform set_config('request.jwt.claims', json_build_object('sub', c)::text, true);
  select count(*) into n from public.comunidades(grupo::text, false); assert n = 0, 'No se descubre la comunidad de quien bloquea';
  begin perform public.publicaciones_comunidad(grupo, null, 20); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'Bloqueo en ambos sentidos';
  perform set_config('request.jwt.claims', json_build_object('sub', a)::text, true); perform public.desbloquear(ac);
  perform set_config('request.jwt.claims', json_build_object('sub', c)::text, true);
  perform public.salir_comunidad(grupo);
  begin perform public.publicaciones_comunidad(grupo, null, 20); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_miembro', 'Salir revoca el acceso';
  begin perform public.comentarios_de(ajena); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'Ni la autoría permite leer los comentarios tras salir';
  begin perform public.reaccionar(compartida); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'Salir revoca también reaccionar';
  perform public.unirse_comunidad(grupo);
  perform public.denunciar('comunidad', grupo::text, 'spam', 'Prueba');
  select count(*) into n from public.denuncias where tipo = 'comunidad' and objetivo = grupo; assert n = 1, 'Denunciar una comunidad';
  update public.perfiles set suspendido = true where user_id = c;
  begin perform public.publicaciones_comunidad(grupo, null, 20); e := null; exception when others then e := sqlerrm; end;
  assert e = 'suspendido', 'Suspendido no usa comunidades';
  update public.perfiles set suspendido = false where user_id = c;
  perform set_config('request.jwt.claims', json_build_object('sub', b)::text, true);
  begin perform public.borrar_comunidad(grupo); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'Solo borra su creadora';
  begin perform public.borrar_publicacion(compartida); e := null; exception when others then e := sqlerrm; end;
  assert e = 'no_encontrado', 'Un miembro no borra publicaciones ajenas';
  update public.comunidades set suspendida = true where id = grupo;
  select count(*) into n from public.comunidades(grupo::text, false); assert n = 0, 'Una comunidad suspendida no aparece';
  update public.comunidades set suspendida = false where id = grupo;
  perform set_config('request.jwt.claims', json_build_object('sub', a)::text, true);
  perform public.borrar_comunidad(grupo);
  select count(*) into n from public.publicaciones where id in (compartida, ajena); assert n = 0, 'Borrar comunidad elimina sus publicaciones';
  select count(*) into n from public.comentarios where id = comentario; assert n = 0, 'Y comentarios en cascada';
  select count(*) into n from public.publicaciones where id = privada; assert n = 1, 'La publicación de seguidores se conserva';
  perform public.crear_comunidad(grupo, 'Cuota ' || grupo, '');
  for i in 1..28 loop perform public.publicar(gen_random_uuid(), 'texto', now(), texto); end loop;
  begin perform public.publicar_comunidad(gen_random_uuid(), 'texto', now(), texto, grupo); e := null; exception when others then e := sqlerrm; end;
  assert e = 'limite', 'La comunidad y seguidores comparten la misma cuota diaria';
  assert not has_table_privilege('authenticated', 'public.comunidades', 'SELECT'), 'Sin lectura directa';
  assert not has_table_privilege('authenticated', 'public.miembros_comunidad', 'INSERT'), 'Sin escritura directa';
  assert not has_function_privilege('authenticated', 'public.social_puede_ver_publicacion(uuid,uuid)', 'EXECUTE'), 'Ayudante privado';
  assert not has_function_privilege('anon', 'public.publicaciones_comunidad(uuid,timestamptz,integer)', 'EXECUTE'), 'Anon no accede al RPC';
end;
$$;

set local role authenticated;
do $$
begin
  begin perform 1 from public.comunidades; raise exception 'No se denegó el acceso directo'; exception when insufficient_privilege then null; end;
  begin perform public.social_es_miembro(gen_random_uuid(), gen_random_uuid()); raise exception 'No se denegó el ayudante'; exception when insufficient_privilege then null; end;
end;
$$;
reset role;
select 'PRUEBAS_COMUNIDADES_OK' as resultado;
rollback;
