/* Registro visual y típicas compartidas. Solo perfiles efímeros y datos sintéticos. */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright')
const { navegar } = require('./navegar.cjs')
const salida = process.env.APPFIT_UI_OUTPUT || '/tmp/appfit-registro-visual'
async function datos(page) {
  return page.evaluate(async () => JSON.parse(JSON.stringify(await (await import('/src/shared/lib/backup.ts')).exportarBackup())))
}
async function captura(page, nombre) {
  await page.evaluate(() => document.fonts.ready)
  const problemas = await page.evaluate(() => {
    const visibles = [...document.querySelectorAll('button,input,textarea,select,[role="dialog"]')].filter(e => e.getClientRects().length && !e.closest('[inert]'))
    return {
      overflow: document.documentElement.scrollWidth > innerWidth || visibles.some(e => e.matches('[role="dialog"]') && e.scrollWidth > e.clientWidth + 1),
      tacto: visibles.filter(e => e.matches('button') && (e.getBoundingClientRect().height < 43.9 || e.getBoundingClientRect().width < 43.9)).map(e => e.getAttribute('aria-label') || e.textContent),
    }
  })
  assert.deepEqual(problemas, { overflow: false, tacto: [] })
  await page.screenshot({ path: path.join(salida, `${nombre}.png`), animations: 'disabled' })
}
async function esperarEntradas(page, cantidad) {
  await page.waitForFunction(async n => (await (await import('/src/shared/lib/backup.ts')).exportarBackup()).entries.length === n, cantidad)
}
async function main() {
  fs.mkdirSync(salida, { recursive: true })
  const browser = await chromium.launch({ executablePath: process.env.APPFIT_CHROMIUM || '/usr/bin/chromium', args: ['--no-sandbox', '--host-resolver-rules=MAP appfit-test.localhost 127.0.0.1'] })
  const vistas = [320, 375, 430].flatMap(width => ['light', 'dark'].map(colorScheme => ({ width, colorScheme })))
  vistas.push({ width: 375, colorScheme: 'dark', grande: true })
  try {
    for (const vista of vistas) {
      const etiqueta = `${vista.width}-${vista.colorScheme}${vista.grande ? '-texto200' : ''}`
      if (process.env.APPFIT_UI_CASE && process.env.APPFIT_UI_CASE !== etiqueta) continue
      const context = await browser.newContext({ viewport: { width: vista.width, height: 932 }, colorScheme: vista.colorScheme, reducedMotion: 'reduce', serviceWorkers: 'block', locale: 'es-ES' })
      const page = await context.newPage()
      page.setDefaultTimeout(12000)
      const errores = []
      page.on('pageerror', e => errores.push(e.message))
      try {
        await context.route('**/world.openfoodfacts.org/**', r => r.abort())
        await page.goto('http://appfit-test.localhost:5173')
        await page.getByRole('button', { name: 'Registrar peso', exact: true }).waitFor()
        await navegar(page, 'Nutrición')
        if (vista.grande) await page.addStyleTag({ content: 'html { font-size: 200% !important; }' })
        await page.getByRole('button', { name: 'Añadir comida', exact: true }).click()
        let tarea = page.getByRole('dialog', { name: 'Añadir comida', exact: true })
        await tarea.getByText('Guarda un alimento o plato habitual para tenerlo aquí.', { exact: true }).waitFor()
        await captura(page, `${etiqueta}-vacio`)
        await tarea.getByRole('button', { name: 'Cancelar', exact: true }).click()
        await tarea.waitFor({ state: 'detached' })
        await page.evaluate(async () => {
          const foods = await import('/src/features/nutricion/data/foodsRepo.ts')
          const meals = await import('/src/features/nutricion/data/mealsRepo.ts')
          const entries = await import('/src/features/nutricion/data/entriesRepo.ts')
          const { todayISO, addDays } = await import('/src/shared/lib/dates.ts')
          const item = (nombre, gramos, kcal100 = 100) => ({ nombre, gramos, kcal100, prot100: 10, carb100: 10, grasa100: 2, categoria: 'Otros', fuenteSiNuevo: 'manual' })
          for (const nombre of ['Arroz de prueba', 'Huevo de prueba', 'Aguacate de prueba']) await foods.crear({ nombre, kcal100: 100, prot100: 10, carb100: 10, grasa100: 2, categoria: 'Otros', fuente: 'manual' })
          for (const [nombre, comida] of [['Café con leche', 'desayuno'], ['Mi plato de pasta habitual con un nombre muy largo para comprobar el espacio', 'comida'], ['Mi yogur', 'cena']]) await meals.crearDesdeRevision({ nombre, comida, items: [item(nombre, 150)] })
          for (const dias of [1, 3, 5]) await entries.guardarComida({ fecha: addDays(todayISO(), -dias), comida: 'desayuno', items: [item('Avena de prueba', 40), item('Leche de prueba', 200)] })
        })
        const original = await datos(page)
        // La guardada de desayuno y la sugerida aparecen en los cuatro destinos; confirmar usa ese destino y Deshacer es aislado.
        for (const [destino, titulo] of [['desayuno', 'Desayuno'], ['comida', 'Comida'], ['cena', 'Cena'], ['snack', 'Snack']]) {
          await page.getByRole('button', { name: `Comidas típicas de ${destino}`, exact: true }).click()
          const selector = page.getByRole('dialog', { name: 'Comidas típicas', exact: true })
          await selector.getByRole('button', { name: /^Café con leche/ }).waitFor()
          await selector.getByRole('button', { name: /^Avena de prueba \+ Leche de prueba/ }).waitFor()
          await captura(page, `${etiqueta}-tipicas-${destino}`)
          await selector.getByRole('button', { name: /^Café con leche/ }).click()
          await selector.waitFor({ state: 'detached' })
          const preview = page.getByRole('dialog', { name: 'Añadir comida típica', exact: true })
          await preview.getByRole('button', { name: `Añadir a ${titulo}`, exact: true }).click()
          await preview.waitFor({ state: 'detached' })
          await esperarEntradas(page, original.entries.length + 1)
          const nuevas = (await datos(page)).entries.filter(e => !original.entries.some(o => o.id === e.id))
          assert.equal(nuevas.length, 1)
          assert.equal(nuevas[0].comida, destino)
          assert.equal(nuevas[0].nombre, 'Café con leche')
          await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
          await esperarEntradas(page, original.entries.length)
          assert.deepEqual((await datos(page)).entries, original.entries)
        }
        await page.getByRole('button', { name: 'Añadir comida', exact: true }).click()
        tarea = page.getByRole('dialog', { name: 'Añadir comida', exact: true })
        await tarea.getByRole('combobox', { name: 'Comida del día', exact: true }).selectOption('cena')
        const tipicas = tarea.getByRole('region', { name: 'Tus comidas típicas', exact: true })
        assert.equal(await tipicas.locator('ul button').count(), 2)
        await tipicas.getByRole('button', { name: 'Ver todas', exact: true }).click()
        const todas = page.getByRole('dialog', { name: 'Comidas típicas', exact: true })
        assert.equal(await todas.locator('ul button').count(), 4)
        await page.keyboard.press('Escape')
        await todas.waitFor({ state: 'detached' })
        const texto = tarea.getByRole('textbox', { name: 'Describe lo que has comido', exact: true })
        await texto.fill('200 g de arroz de prueba\n100 g de huevo de prueba\n75 g de aguacate de prueba')
        assert.equal(await tarea.getByRole('list', { name: 'Separación de alimentos', exact: true }).count(), 0)
        await tarea.getByRole('button', { name: 'Escanear producto', exact: true }).click()
        const scanner = page.getByRole('dialog', { name: 'Escanear producto', exact: true })
        await scanner.waitFor()
        await page.keyboard.press('Escape')
        await scanner.waitFor({ state: 'detached' })
        assert.ok((await texto.inputValue()).includes('200 g de arroz'))
        await tarea.getByRole('tab', { name: 'Escribir', exact: true }).focus()
        await page.keyboard.press('ArrowRight')
        assert.equal(await tarea.getByRole('tab', { name: 'Buscar', exact: true }).getAttribute('aria-selected'), 'true')
        await tarea.getByRole('button', { name: 'Escanear producto', exact: true }).waitFor()
        await tarea.getByRole('tab', { name: 'Escribir', exact: true }).click()
        const franja = await tarea.getByRole('tablist', { name: 'Cómo añadir comida', exact: true }).boundingBox()
        const activa = await tarea.getByRole('tab', { name: 'Escribir', exact: true }).boundingBox()
        assert.ok(activa.x >= franja.x - 1 && activa.x + activa.width <= franja.x + franja.width + 1, 'la pestaña activa se lee completa con texto ampliado')
        await captura(page, `${etiqueta}-escribir`)
        await tarea.getByRole('button', { name: 'Revisar 3 alimentos', exact: true }).click()
        const editarArroz = tarea.getByRole('button', { name: 'Editar Arroz de prueba', exact: true })
        await editarArroz.waitFor()
        assert.equal(await editarArroz.getAttribute('aria-expanded'), 'false')
        assert.equal(await tarea.getByRole('textbox', { name: 'gramos', exact: true }).count(), 0)
        await captura(page, `${etiqueta}-revision`)
        await editarArroz.click()
        const gramos = tarea.getByRole('textbox', { name: 'gramos', exact: true })
        await gramos.fill('250')
        await gramos.blur()
        await captura(page, `${etiqueta}-editar`)
        await editarArroz.click()
        await tarea.getByRole('button', { name: 'Poner nombre al plato', exact: true }).click()
        await tarea.getByRole('textbox', { name: 'Nombre del plato (opcional)', exact: true }).fill('Mi plato de prueba')
        await tarea.getByRole('checkbox', { name: 'Guardar como comida típica', exact: true }).check()
        await tarea.getByRole('button', { name: /^Añadir a cena ·/ }).click()
        await tarea.waitFor({ state: 'detached' })
        const guardado = await datos(page)
        const nuevas = guardado.entries.filter(e => !original.entries.some(o => o.id === e.id))
        assert.equal(nuevas.length, 3)
        assert.ok(nuevas.every(e => e.comida === 'cena' && e.nombrePlato === 'Mi plato de prueba'))
        assert.equal(nuevas.find(e => e.nombre === 'Arroz de prueba').gramos, 250)
        assert.equal(guardado.meals.length, original.meals.length + 1)
        // Crear una típica no pide un tipo de comida y no escribe diario ni objetivos.
        await page.getByRole('button', { name: 'Añadir comida', exact: true }).click()
        tarea = page.getByRole('dialog', { name: 'Añadir comida', exact: true })
        await tarea.getByRole('button', { name: 'Nueva comida típica', exact: true }).click()
        const crear = page.getByRole('dialog', { name: 'Nueva comida típica', exact: true })
        assert.equal(await crear.getByRole('combobox', { name: 'Comida del día', exact: true }).count(), 0)
        await crear.getByRole('textbox', { name: 'Nombre de la comida típica', exact: true }).fill('Mi arroz rápido')
        await crear.getByRole('textbox', { name: 'Describe lo que has comido', exact: true }).fill('100 g de arroz de prueba')
        await crear.getByRole('button', { name: 'Revisar 1 alimento', exact: true }).click()
        await crear.getByRole('button', { name: /^Guardar comida típica ·/ }).click()
        await crear.waitFor({ state: 'detached' })
        const trasCrear = await datos(page)
        assert.deepEqual(trasCrear.entries, guardado.entries)
        assert.deepEqual(trasCrear.objetivosDia, guardado.objetivosDia)
        assert.equal(trasCrear.meals.find(m => m.nombre === 'Mi arroz rápido').comida, undefined)
        // Los datos obligatorios siguen desplegados; cancelar conserva el diario.
        await tarea.getByRole('textbox', { name: 'Describe lo que has comido', exact: true }).fill('100 g de alimento inexistente de prueba')
        await tarea.getByRole('button', { name: 'Revisar 1 alimento', exact: true }).click()
        assert.equal(await tarea.getByRole('button', { name: 'Editar alimento inexistente de prueba', exact: true }).getAttribute('aria-expanded'), 'true')
        await tarea.getByRole('combobox', { name: 'Categoría', exact: true }).waitFor()
        assert.equal(await tarea.getByRole('button', { name: /^Añadir a / }).isDisabled(), true)
        await captura(page, `${etiqueta}-pendiente`)
        await tarea.getByRole('button', { name: 'Cancelar', exact: true }).click()
        await page.getByRole('dialog', { name: '¿Descartar los cambios?', exact: true }).getByRole('button', { name: 'Descartar', exact: true }).click()
        await tarea.waitFor({ state: 'detached' })
        assert.deepEqual((await datos(page)).entries, guardado.entries)
        await page.getByRole('tab', { name: 'Alimentos', exact: true }).click()
        await page.getByRole('radio', { name: 'Típicas', exact: true }).click()
        assert.equal(await page.getByRole('radiogroup', { name: 'Comida habitual', exact: true }).count(), 0)
        await page.getByRole('button', { name: /^Mi arroz rápido/ }).waitFor()
        await captura(page, `${etiqueta}-biblioteca`)
        const antesRecarga = await datos(page)
        await page.reload()
        const despuesRecarga = await datos(page)
        delete antesRecarga.exportedAt; delete despuesRecarga.exportedAt
        assert.deepEqual(despuesRecarga, antesRecarga)
        assert.deepEqual(errores, [])
        console.log(`${etiqueta}: correcto`)
      } catch (e) {
        await page.screenshot({ path: path.join(salida, `${etiqueta}-fallo.png`), animations: 'disabled' }).catch(() => {})
        throw new Error(`${etiqueta}: ${e.message}`, { cause: e })
      } finally { await context.close() }
    }
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
